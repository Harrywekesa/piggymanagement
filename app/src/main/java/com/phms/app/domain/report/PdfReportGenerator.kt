package com.phms.app.domain.report

import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import androidx.core.content.FileProvider
import com.phms.app.ui.viewmodel.ComprehensiveReport
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object PdfReportGenerator {

    fun generateAndShareReport(
        context: Context,
        farmName: String,
        report: ComprehensiveReport?,
        periodLabel: String,
        startDateMs: Long,
        endDateMs: Long
    ) {
        val pdfFile = generatePdf(context, farmName, report, periodLabel, startDateMs, endDateMs) ?: return
        val uri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            pdfFile
        )

        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, "$farmName - Farm Performance Report ($periodLabel)")
            putExtra(Intent.EXTRA_TEXT, "Attached is the latest performance report for $farmName ($periodLabel).")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }

        val chooser = Intent.createChooser(intent, "Share Farm Report PDF via")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        context.startActivity(chooser)
    }

    fun shareTextSummary(
        context: Context,
        farmName: String,
        report: ComprehensiveReport?,
        periodLabel: String,
        startDateMs: Long,
        endDateMs: Long
    ) {
        val dateFormat = SimpleDateFormat("d MMM yyyy", Locale.getDefault())
        val dateRangeStr = if (startDateMs == 0L) "All Time Records" else "${dateFormat.format(Date(startDateMs))} - ${dateFormat.format(Date(endDateMs))}"
        val pnl = report?.pnl
        val herd = report?.herd
        val feed = report?.feedGrowth

        val summary = buildString {
            appendLine("🐷 $farmName - Farm Performance Report")
            appendLine("📅 Period: $periodLabel ($dateRangeStr)")
            appendLine()
            appendLine("📊 HERD CENSUS")
            appendLine("• Active Herd: ${herd?.totalActivePigs ?: 0} pigs")
            appendLine("• Piglets: ${herd?.pigletsCount ?: 0} | Weaners: ${herd?.weanersCount ?: 0} | Finishers: ${herd?.finishersCount ?: 0}")
            appendLine("• Sows & Gilts: ${(herd?.sowsCount ?: 0) + (herd?.giltsCount ?: 0)} | Boars: ${herd?.boarsCount ?: 0}")
            if ((herd?.totalBornAliveInPeriod ?: 0) > 0) {
                appendLine("• Born Alive: ${herd?.totalBornAliveInPeriod} | Stillborn: ${herd?.totalStillbornInPeriod} | Weaned: ${herd?.totalWeanedInPeriod}")
            }
            appendLine()
            appendLine("🌾 FEED & GROWTH EFFICIENCY")
            appendLine("• Total Feed Consumed: ${String.format(Locale.US, "%.1f", feed?.totalFeedConsumedKg ?: 0.0)} kg")
            appendLine("• Total Feed Cost: KSh ${feed?.feedCostTotal?.toInt() ?: 0}")
            appendLine("• Average Daily Gain (ADG): ${String.format(Locale.US, "%.2f", feed?.avgDailyGainKg ?: 0.45)} kg/day")
            appendLine("• Feed Conversion Ratio (FCR): ${String.format(Locale.US, "%.2f", feed?.feedConversionRatio ?: 2.8)}")
            appendLine()
            appendLine("💰 FINANCIAL PROFIT & LOSS")
            appendLine("• Sales Revenue: KSh ${pnl?.totalRevenue?.toInt() ?: 0}")
            appendLine("• Feed Expenses: -KSh ${pnl?.feedCost?.toInt() ?: 0}")
            appendLine("• Health & Vet: -KSh ${pnl?.healthCost?.toInt() ?: 0}")
            appendLine("• Labor & Overhead (Est): -KSh ${pnl?.estimatedLaborCost?.toInt() ?: 0}")
            val net = pnl?.netProfit?.toInt() ?: 0
            val profitIcon = if (net >= 0) "✅" else "⚠️"
            appendLine("• NET PROFIT/LOSS: $profitIcon KSh $net")
            appendLine()
            appendLine("Generated by PHMS (Pig Herd Management System)")
        }

        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, "$farmName Report ($periodLabel)")
            putExtra(Intent.EXTRA_TEXT, summary)
        }
        val chooser = Intent.createChooser(intent, "Share Report via")
        chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        context.startActivity(chooser)
    }

    private fun generatePdf(
        context: Context,
        farmName: String,
        report: ComprehensiveReport?,
        periodLabel: String,
        startDateMs: Long,
        endDateMs: Long
    ): File? {
        val document = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // Standard A4 (points)
        val page = document.startPage(pageInfo)
        val canvas = page.canvas

        val paint = Paint(Paint.ANTI_ALIAS_FLAG)
        val dateFormat = SimpleDateFormat("d MMM yyyy", Locale.getDefault())
        val generatedAtFormat = SimpleDateFormat("d MMM yyyy, HH:mm", Locale.getDefault())
        val dateRangeStr = if (startDateMs == 0L) "All Time Records" else "${dateFormat.format(Date(startDateMs))} - ${dateFormat.format(Date(endDateMs))}"

        // Header Banner (Dark Green)
        paint.color = Color.rgb(27, 94, 32)
        canvas.drawRect(0f, 0f, 595f, 100f, paint)

        // Accent strip
        paint.color = Color.rgb(76, 175, 80)
        canvas.drawRect(0f, 100f, 595f, 106f, paint)

        // Title
        paint.color = Color.WHITE
        paint.textSize = 22f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        canvas.drawText(farmName, 32f, 42f, paint)

        paint.textSize = 13f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
        canvas.drawText("Farm Performance & Management Report", 32f, 64f, paint)

        paint.textSize = 10f
        paint.color = Color.rgb(200, 230, 201)
        canvas.drawText("Period: $periodLabel ($dateRangeStr)  •  Generated: ${generatedAtFormat.format(Date())}", 32f, 84f, paint)

        var y = 135f

        fun drawSectionHeader(title: String, icon: String) {
            paint.color = Color.rgb(240, 244, 240)
            canvas.drawRoundRect(30f, y - 14f, 565f, y + 14f, 6f, 6f, paint)
            paint.color = Color.rgb(27, 94, 32)
            paint.textSize = 13f
            paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            canvas.drawText("$icon  $title", 40f, y + 5f, paint)
            y += 32f
        }

        fun drawTableRow(label: String, value: String, isBold: Boolean = false, isPositive: Boolean? = null) {
            paint.textSize = 11f
            paint.typeface = if (isBold) Typeface.create(Typeface.DEFAULT, Typeface.BOLD) else Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            paint.color = Color.rgb(50, 50, 50)
            canvas.drawText(label, 42f, y, paint)

            paint.color = when (isPositive) {
                true -> Color.rgb(46, 125, 50)
                false -> Color.rgb(198, 40, 40)
                else -> Color.rgb(20, 20, 20)
            }
            val textWidth = paint.measureText(value)
            canvas.drawText(value, 555f - textWidth, y, paint)

            paint.color = Color.rgb(230, 230, 230)
            canvas.drawLine(42f, y + 6f, 555f, y + 6f, paint)
            y += 20f
        }

        // Section 1: Financial Performance (P&L)
        drawSectionHeader("Financial Profit & Loss Statement", "💰")
        val pnl = report?.pnl
        drawTableRow("Gross Sales Revenue", "KSh ${pnl?.totalRevenue?.toInt() ?: 0}", isPositive = true)
        drawTableRow("Feed Procurement & Ingredients", "- KSh ${pnl?.feedCost?.toInt() ?: 0}", isPositive = false)
        drawTableRow("Veterinary & Medication Expenses", "- KSh ${pnl?.healthCost?.toInt() ?: 0}", isPositive = false)
        drawTableRow("Labor, Utilities & Operational Overhead (Est.)", "- KSh ${pnl?.estimatedLaborCost?.toInt() ?: 0}", isPositive = false)
        val net = pnl?.netProfit?.toInt() ?: 0
        drawTableRow("NET OPERATING PROFIT / LOSS", "KSh $net", isBold = true, isPositive = net >= 0)

        y += 15f

        // Section 2: Herd Inventory & Census
        drawSectionHeader("Herd Census & Category Breakdown", "📊")
        val herd = report?.herd
        drawTableRow("Total Active Herd", "${herd?.totalActivePigs ?: 0} pigs", isBold = true)
        drawTableRow("Piglets (< 4 weeks)", "${herd?.pigletsCount ?: 0} pigs")
        drawTableRow("Weaners (4 - 10 weeks)", "${herd?.weanersCount ?: 0} pigs")
        drawTableRow("Growers & Finishers", "${herd?.finishersCount ?: 0} pigs")
        drawTableRow("Breeding Sows & Gilts", "${(herd?.sowsCount ?: 0) + (herd?.giltsCount ?: 0)} heads")
        drawTableRow("Breeding Boars", "${herd?.boarsCount ?: 0} heads")
        if ((herd?.totalBornAliveInPeriod ?: 0) > 0 || (herd?.totalWeanedInPeriod ?: 0) > 0) {
            drawTableRow("Litter Output: Born Alive / Stillborn / Weaned", "${herd?.totalBornAliveInPeriod ?: 0} / ${herd?.totalStillbornInPeriod ?: 0} / ${herd?.totalWeanedInPeriod ?: 0}")
        }

        y += 15f

        // Section 3: Feed Efficiency & Growth
        drawSectionHeader("Feed & Conversion Performance", "🌾")
        val feed = report?.feedGrowth
        drawTableRow("Total Feed Consumed in Period", "${String.format(Locale.US, "%.1f", feed?.totalFeedConsumedKg ?: 0.0)} kg")
        drawTableRow("Total Feed Expense", "KSh ${feed?.feedCostTotal?.toInt() ?: 0}")
        drawTableRow("Estimated Herd Weight Gained", "${String.format(Locale.US, "%.1f", feed?.totalWeightGainedKg ?: 0.0)} kg")
        drawTableRow("Average Daily Gain (ADG)", "${String.format(Locale.US, "%.2f", feed?.avgDailyGainKg ?: 0.45)} kg/day", isBold = true)
        drawTableRow("Feed Conversion Ratio (FCR)", "${String.format(Locale.US, "%.2f", feed?.feedConversionRatio ?: 2.8)} kg feed/kg gain", isBold = true)

        y += 15f

        // Section 4: Health & Biosecurity
        drawSectionHeader("Health, Biosecurity & Medication", "🩺")
        val health = report?.health
        drawTableRow("Health & Treatment Events Logged", "${health?.totalEventsCount ?: 0} events")
        drawTableRow("Deaths / Mortality in Period", "${health?.totalDeathsCount ?: 0} pigs")
        drawTableRow("Herd Mortality Rate", "${String.format(Locale.US, "%.1f%%", health?.mortalityRatePct ?: 0.0)}", isPositive = (health?.mortalityRatePct ?: 0.0) < 5.0)
        drawTableRow("Pigs Under Medication Withdrawal", "${health?.activeWithdrawalCount ?: 0} pigs", isBold = (health?.activeWithdrawalCount ?: 0) > 0)

        // Footer
        paint.color = Color.rgb(120, 120, 120)
        paint.textSize = 9f
        paint.typeface = Typeface.create(Typeface.DEFAULT, Typeface.ITALIC)
        canvas.drawText("Generated by PHMS (Pig Herd Management System) • Confidential Farm Records", 32f, 815f, paint)

        document.finishPage(page)

        return try {
            val reportsDir = File(context.cacheDir, "reports")
            if (!reportsDir.exists()) reportsDir.mkdirs()
            val file = File(reportsDir, "PHMS_Report_${System.currentTimeMillis()}.pdf")
            FileOutputStream(file).use { out ->
                document.writeTo(out)
            }
            document.close()
            file
        } catch (e: Exception) {
            e.printStackTrace()
            document.close()
            null
        }
    }
}
